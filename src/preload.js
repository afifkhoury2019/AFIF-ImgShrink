"use strict";
const { contextBridge, ipcRenderer, webUtils } = require("electron");
const on = (ch) => (cb) => ipcRenderer.on(ch, (_e, d) => cb(d));
contextBridge.exposeInMainWorld("shrink", {
  pendingFiles: () => ipcRenderer.invoke("pending-files"),
  pickImage: () => ipcRenderer.invoke("pick-image"),
  pickOutput: (def) => ipcRenderer.invoke("pick-output", def),
  analyze: (f) => ipcRenderer.invoke("analyze", f),
  freeSpace: (d) => ipcRenderer.invoke("free-space", d),
  exists: (p) => ipcRenderer.invoke("exists", p),
  start: (o) => ipcRenderer.invoke("start", o),
  cancel: () => ipcRenderer.invoke("cancel"),
  showItem: (p) => ipcRenderer.invoke("show-item", p),
  openUrl: (u) => ipcRenderer.invoke("open-url", u),
  settings: () => ipcRenderer.invoke("settings"),
  setSettings: (p) => ipcRenderer.invoke("set-settings", p),
  appInfo: () => ipcRenderer.invoke("app-info"),
  taskbar: (f) => ipcRenderer.invoke("taskbar", f),
  expandScript: () => ipcRenderer.invoke("expand-script"),
  startTab: () => ipcRenderer.invoke("start-tab"),
  diskList: (all) => ipcRenderer.invoke("disk-list", all),
  pickSource: (d) => ipcRenderer.invoke("pick-source", d),
  pickSaveImg: (d) => ipcRenderer.invoke("pick-save-img", d),
  inspect: (f) => ipcRenderer.invoke("inspect", f),
  diskStart: (op, o) => ipcRenderer.invoke("disk-start", op, o),
  diskCancel: () => ipcRenderer.invoke("disk-cancel"),
  hash: (f, a) => ipcRenderer.invoke("hash", f, a),
  hashCancel: () => ipcRenderer.invoke("hash-cancel"),
  relaunchAdmin: () => ipcRenderer.invoke("relaunch-admin"),
  launchUsb: () => ipcRenderer.invoke("launch-usb"),
  onDiskProgress: on("disk-progress"), onHashProgress: on("hash-progress"),
  pathForFile: (f) => { try { return webUtils.getPathForFile(f); } catch { return null; } },
  onLog: on("job-log"), onStep: on("job-step"), onProgress: on("job-progress"), onOpenFile: on("open-file"),
});
